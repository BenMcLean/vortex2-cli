"""Regenerate src/vortexlib/_spec_data.py from the files in spec/.

The library embeds the spec data so that it never touches the file system.
Run after changing anything in spec/:  python tools/gen_data.py
"""

import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
spec = root / "spec"
layout = json.loads((spec / "layout.json").read_text(encoding="utf-8"))
template = bytes.fromhex((spec / "vw2_template.hex").read_text())
defaults = json.loads(
	(spec / "device_factory_defaults.json").read_text(encoding="utf-8")
)
slot0 = bytes.fromhex(defaults["slots"]["0"])

out = [
	'"""GENERATED by tools/gen_data.py from spec/ -- do not edit."""',
	"",
	f"LAYOUT_JSON = {json.dumps(layout, separators=(',', ':'))!r}",
	f"VW2_TEMPLATE_HEX = {template.hex()!r}",
	f"FACTORY_SLOT0_HEX = {slot0.hex()!r}",
	"",
]
(root / "src" / "vortexlib" / "_spec_data.py").write_text(
	"\n".join(out), encoding="utf-8"
)
print("wrote _spec_data.py")
